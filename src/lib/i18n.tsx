export type MessageKey = keyof (typeof messages)["en"];

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in vars ? String(vars[name]) : m,
  );
}

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const dict = messages[locale] ?? messages.en;
  const en = messages.en as Record<string, string>;
  const value = (dict as Record<string, string>)[key as string] ?? en[key as string] ?? String(key);
  return interpolate(value, vars);
}


/** Locale-aware formatting helpers so numbers/dates follow the UI language. */
export function useI18n() {
  const { settings } = useSettings();
  const locale = (settings.language === "ar" ? "ar" : "en") as Locale;
  return useMemo(
    () => ({
      locale,
      dir: locale === "ar" ? ("rtl" as const) : ("ltr" as const),
      t: (key: MessageKey, vars?: Record<string, string | number>) =>
        translate(locale, key, vars),
      formatNumber: (value: number, options?: Intl.NumberFormatOptions) =>
        new Intl.NumberFormat(locale === "ar" ? "ar-EG" : "en-US", options).format(value),
      formatDate: (value: number | Date, options?: Intl.DateTimeFormatOptions) =>
        new Intl.DateTimeFormat(locale === "ar" ? "ar-EG" : "en-US", options).format(value),
    }),
    [locale],
  );
}

/** Shorthand for components that only need the translate function. */
export function useT() {
  return useI18n().t;
}
